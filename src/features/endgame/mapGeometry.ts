/**
 * 战国七雄示意版图（手绘多边形）
 * ===========================================================================
 * 为什么是"示意版图"而不是描摹实拍地图：
 *   实拍/扫描地图无法自动矢量化，手工描边叠加会显得很脏；
 *   而交互需要每个国家可独立命中、可独立过渡。
 *   所以照片只做背景质感层（低饱和 + 压暗），
 *   交互层用这组手绘多边形 —— 相对方位严格遵循真实地理：
 *     秦据西陲、赵在河北、燕居东北、齐处东滨、魏韩纵横中原、楚有南方。
 *
 * 坐标系：viewBox 0 0 1000 640，与地图照片同向（上北下南）。
 */

export interface MapRegion {
  id: string
  name: string
  /** SVG polygon 顶点 */
  points: string
  /** 标签位置 */
  label: [number, number]
  /** 未被吞并时的底色 */
  color: string
  /** 国都（示意坐标，落在该国轮廓内） */
  capital?: { name: string; x: number; y: number }
}

